#!/usr/bin/env node
/**
 * audit-claude-references.mjs (AISDLC-540) — regenerates the vendor-coupling
 * inventory in docs/audits/2026-10-28-claude-coupling-audit.md.
 *
 * Classifies every case-insensitive `claude` reference in non-test source of
 * orchestrator/src and pipeline-cli/src into:
 *   adapter-layer  - file is part of the Claude Code adapter/spawner/plugin seam
 *   config-default - the vendor default lives in the sanctioned seam files
 *   core-coupling  - everything else (gap list, one proposed seam per file)
 *
 * Usage: node scripts/audit-claude-references.mjs [--write <out.md>]
 */
import { readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { join, relative, resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const SCAN = ['orchestrator/src', 'pipeline-cli/src'];

const ADAPTER = [
  /claude/i, // file name contains claude
  /harness\/adapters\//,
  /orchestrator\/src\/runners\//,
  /runtime\/(default-spawner|spawners\/)/,
  /cli\/commands\/(doctor-checks|init-features|init-templates|mcp-setup)/,
  /attestation\/(harness-transcript|agent-dir-resolver)/,
  /models\/registry/,
  /usage\/replay/,
  /memory-dream\/resolve-dir/,
  /cli\/attestation/,
  /runtime\/attestations\.ts$/,
];
const CONFIG_SEAM = [
  /pipeline-cli\/src\/harness-defaults\.ts$/,
  /orchestrator\/src\/defaults\.ts$/,
];

const SEAMS = [
  [
    /pipeline-cli\/src\/(dispatch|orchestrator)\//,
    'route worker/spawner kind and harness label through the runner-registry (AISDLC-529) instead of string-matching claude kinds',
  ],
  [
    /pipeline-cli\/src\/hierarchy\//,
    'move session launch binary, config dir and role detection behind a HarnessSessionAdapter',
  ],
  [
    /pipeline-cli\/src\/(next-step|review-plan|review-staged|routing|pipeline)\//,
    'resolve reviewer harness via routing table `harness` field and DEFAULT_HARNESS rather than claude-specific branches',
  ],
  [
    /pipeline-cli\/src\/cli\//,
    'read harness/binary from config (substrate contract) instead of claude-named flags and messages',
  ],
  [
    /pipeline-cli\/src\/(attestation|governance|decisions|dor)\//,
    'name the harness via the attestation/verdict `harness` field; keep prose vendor-neutral',
  ],
  [
    /pipeline-cli\/src\/(types|index|execute-pipeline|runtime)/,
    'rename vendor-named exports/types behind neutral aliases and re-export from the adapter module',
  ],
  [
    /orchestrator\/src\//,
    'consume the HarnessAdapter interface in orchestrator/src/harness instead of claude-named paths and strings',
  ],
  [
    /pipeline-cli\/src\//,
    'replace the literal with a harness-defaults.ts constant or config-resolved value',
  ],
];

function walk(d, out) {
  for (const n of readdirSync(d)) {
    const f = join(d, n);
    if (statSync(f).isDirectory()) {
      if (['node_modules', 'dist', '__tests__', '__test-helpers'].includes(n)) continue;
      walk(f, out);
    } else if (/\.(ts|tsx|mjs|js)$/.test(n) && !/\.test\.|\.d\.ts$/.test(n)) out.push(f);
  }
  return out;
}

const isComment = (t) => /^\s*(\/\/|\/?\*)/.test(t);
const buckets = { adapter: [], config: [], core: [] };
for (const root of SCAN) {
  for (const f of walk(join(ROOT, root), []).sort()) {
    const rel = relative(ROOT, f).split('\\').join('/');
    const hits = [];
    readFileSync(f, 'utf8')
      .split('\n')
      .forEach((t, i) => {
        const m = t.match(/claude/gi);
        if (m)
          hits.push({
            line: i + 1,
            text: t.trim().slice(0, 140),
            n: m.length,
            comment: isComment(t),
          });
      });
    if (!hits.length) continue;
    const key = CONFIG_SEAM.some((r) => r.test(rel))
      ? 'config'
      : ADAPTER.some((r) => r.test(rel))
        ? 'adapter'
        : 'core';
    buckets[key].push({ rel, hits, n: hits.reduce((a, h) => a + h.n, 0) });
  }
}

const sum = (b) => b.reduce((a, f) => a + f.n, 0);
const lines = [];
const P = (s = '') => lines.push(s);
P('# Vendor-coupling audit: `claude` references in core paths (AISDLC-540)');
P();
P(
  'Generated by `node scripts/audit-claude-references.mjs --write docs/audits/2026-10-28-claude-coupling-audit.md`.',
);
P(
  'Scope: non-test source under `orchestrator/src` and `pipeline-cli/src`. Counts are case-insensitive occurrences of `claude`.',
);
P();
P('## Summary');
P();
P('| Bucket | Files | Occurrences | Meaning |');
P('|---|---:|---:|---|');
P(
  `| adapter-layer | ${buckets.adapter.length} | ${sum(buckets.adapter)} | Legitimately inside the Claude Code adapter, spawner, runner or init/doctor layer |`,
);
P(
  `| config-default | ${buckets.config.length} | ${sum(buckets.config)} | Vendor defaults now held in the sanctioned seams (\`pipeline-cli/src/harness-defaults.ts\`, \`orchestrator/src/defaults.ts\`) |`,
);
P(
  `| core-coupling | ${buckets.core.length} | ${sum(buckets.core)} | Hardwired in core orchestration paths; gap list below (not fixed here) |`,
);
P(
  `| total | ${Object.values(buckets).reduce((a, b) => a + b.length, 0)} | ${Object.values(buckets).reduce((a, b) => a + sum(b), 0)} | |`,
);
const coreComment = buckets.core.reduce(
  (a, f) => a + f.hits.filter((h) => h.comment).reduce((x, h) => x + h.n, 0),
  0,
);
P();
P(
  `Of the core-coupling occurrences, ${coreComment} are in comments/doc blocks (low severity) and ${sum(buckets.core) - coreComment} are in code or string literals.`,
);
P();
P('## Bucket (b): config-default, closed in this change');
P();
P(
  "Before: `harness: 'claude-code'` was spelled as a literal in 8 core files (`dispatch/reviewer-harness.ts`, `review-staged/verdict.ts`, `review-staged/leaves.ts`, `steps/09-iterate.ts`, `next-step/review-finalize.ts`, `next-step/staged-round.ts`, `orchestrator/reconcile.ts`, `review-plan/executor.ts`), the `claude` binary default in 3 (`dispatch/supervisor.ts`, `cli/hierarchy.ts`, `review-staged/probe-spawner.ts`), and the provenance tool label in `orchestrator/src/provenance.ts`.",
);
P(
  'After: those import `DEFAULT_HARNESS` / `DEFAULT_HARNESS_BINARY` (`pipeline-cli/src/harness-defaults.ts`) or `DEFAULT_TOOL` (`orchestrator/src/defaults.ts`). Values are unchanged, so behavior under Claude Code is identical.',
);
P(
  'Regression guard: `findVendorDefaultViolations` in `scripts/check-substrate-contract.mjs` fails CI when a core file re-introduces such a literal outside an allowlisted seam/adapter file.',
);
P();
P('### Seam files');
P();
for (const f of buckets.config) P(`- \`${f.rel}\`: ${f.n}`);
P();
P('## Bucket (a): adapter-layer (no action)');
P();
P('| File | Occurrences |');
P('|---|---:|');
for (const f of buckets.adapter) P(`| \`${f.rel}\` | ${f.n} |`);
P();
P('## Bucket (c): core-coupling gap list');
P();
P(
  "Evidence is the first lines per file (code before comments). Each entry has a one-line proposed seam. No implementation and no backlog tasks were filed by this change; filing follow-ups is the operator's call.",
);
P();
const sorted = [...buckets.core].sort((a, b) => b.n - a.n || a.rel.localeCompare(b.rel));
for (const f of sorted) {
  const seam = SEAMS.find(([r]) => r.test(f.rel))[1];
  const ev = [...f.hits]
    .sort((a, b) => Number(a.comment) - Number(b.comment))
    .slice(0, 3)
    .sort((a, b) => a.line - b.line);
  P(`### \`${f.rel}\` (${f.n})`);
  P();
  for (const h of ev)
    P(`- L${h.line}${h.comment ? ' (comment)' : ''}: \`${h.text.replace(/`/g, "'")}\``);
  P(`- Proposed seam: ${seam}.`);
  P();
}
const md = lines.join('\n');
const w = process.argv.indexOf('--write');
if (w > 0) writeFileSync(resolve(process.argv[w + 1]), md);
else process.stdout.write(md);
