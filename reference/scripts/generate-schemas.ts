/**
 * Reads spec/schemas/*.schema.json and generates src/core/generated-schemas.ts
 * so schemas are inlined at build time — no fs.readFileSync at runtime.
 */

import { readdirSync, readFileSync, renameSync, writeFileSync, unlinkSync } from 'node:fs';
import { format, resolveConfig } from 'prettier';
import { resolve, dirname, basename } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
export const SCHEMA_DIR = resolve(__dirname, '../../spec/schemas');
export const OUTPUT = resolve(__dirname, '../src/core/generated-schemas.ts');

export function toCamelCase(filename: string): string {
  // "agent-role.schema.json" → "agentRoleSchema"
  // "dor-config.v1.schema.json" → "dorConfigV1Schema"
  return (
    filename
      .replace('.schema.json', '')
      .replace(/\.([a-z0-9])/g, (_, c: string) => c.toUpperCase())
      .replace(/-([a-z])/g, (_, c: string) => c.toUpperCase()) + 'Schema'
  );
}

export function renderSchemas(schemaDir: string): { source: string; count: number } {
  const files = readdirSync(schemaDir)
    .filter((f) => f.endsWith('.schema.json'))
    .sort();

  const exports: string[] = [];
  const mapEntries: string[] = [];

  for (const file of files) {
    const content = readFileSync(resolve(schemaDir, file), 'utf-8');
    const varName = toCamelCase(file);
    exports.push(`export const ${varName} = ${content.trimEnd()} as const;\n`);
    mapEntries.push(`  '${file}': ${varName},`);
  }

  const source = `// AUTO-GENERATED by scripts/generate-schemas.ts — do not edit manually.

${exports.join('\n')}
export const SCHEMAS: Record<string, object> = {
${mapEntries.join('\n')}
};
`;
  return { source, count: files.length };
}

/**
 * Generates and formats the output in memory, then replaces the target
 * atomically (temp file + rename). The target is left untouched when the
 * content is unchanged, so concurrent readers never see a torn file.
 * Returns true when the file was (re)written.
 */
export async function generate(schemaDir: string, output: string): Promise<boolean> {
  const { source, count } = renderSchemas(schemaDir);
  const config = (await resolveConfig(output)) ?? {};
  const formatted = await format(source, { ...config, filepath: output });

  let existing: string | null = null;
  try {
    existing = readFileSync(output, 'utf-8');
  } catch {
    existing = null;
  }
  if (existing === formatted) {
    console.log(`Unchanged ${output} (${count} schemas)`);
    return false;
  }

  const tmp = `${output}.${process.pid}.tmp`;
  try {
    writeFileSync(tmp, formatted, 'utf-8');
    renameSync(tmp, output);
  } catch (err) {
    try {
      unlinkSync(tmp);
    } catch {
      /* temp already gone */
    }
    throw err;
  }
  console.log(`Generated ${output} (${count} schemas)`);
  return true;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === resolve(process.argv[1])) {
  await generate(SCHEMA_DIR, OUTPUT);
}
