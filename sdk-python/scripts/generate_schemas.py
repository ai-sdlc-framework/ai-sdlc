#!/usr/bin/env python3
"""
Reads spec/schemas/*.schema.json and generates
src/ai_sdlc/core/_generated_schemas.py so schemas are inlined at build time.
"""

import json
import pprint
from pathlib import Path

SCHEMA_DIR = Path(__file__).resolve().parent.parent.parent / "spec" / "schemas"
OUTPUT = (
    Path(__file__).resolve().parent.parent / "src" / "ai_sdlc" / "core" / "_generated_schemas.py"
)


# The resource schemas the Python SDK embeds: the eleven resource kinds of the
# reference plus the schemas they reference (AISDLC-1302, AISDLC-1308).
SDK_SCHEMAS = [
    "adapter-binding",
    "agent-role",
    "autonomy-policy",
    "capabilities-config.v1",
    "common",
    "compliance-posture.v1",
    "design-intent-document",
    "design-system-binding",
    "dor-config.v1",
    "journey.v1",
    "judgment-config.v1",
    "pipeline",
    "quality-gate",
]


def to_snake_case(filename: str) -> str:
    """'agent-role.schema.json' → 'agent_role_schema', 'dor-config.v1…' → 'dor_config_v1_schema'"""
    name = filename.replace(".schema.json", "").replace("-", "_").replace(".", "_")
    return f"{name}_schema"


def main() -> None:
    files = [SCHEMA_DIR / f"{n}.schema.json" for n in SDK_SCHEMAS]
    if not files:
        raise RuntimeError(f"No schema files found in {SCHEMA_DIR}")

    lines = [
        "# AUTO-GENERATED by scripts/generate_schemas.py — do not edit manually.",
        "# ruff: noqa",
        "# fmt: off",
        "",
        "from __future__ import annotations",
        "",
        "from typing import Any",
        "",
    ]

    var_names: list[str] = []
    map_entries: list[str] = []

    for f in files:
        content = json.loads(f.read_text())
        var_name = to_snake_case(f.name)
        var_names.append(var_name)
        lines.append(f"{var_name}: dict[str, Any] = {pprint.pformat(content, width=120)}")
        lines.append("")
        map_entries.append(f'    "{f.name}": {var_name},')

    lines.append("SCHEMAS: dict[str, dict[str, Any]] = {")
    lines.extend(map_entries)
    lines.append("}")
    lines.append("")

    OUTPUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"Generated {OUTPUT} ({len(files)} schemas)")


if __name__ == "__main__":
    main()
